import express from "express";
import { homePage } from "../controllers/homeController.js";
import { showLogin, login, logout } from "../controllers/authController.js";
import { dashboard } from "../controllers/dashboardController.js";
import { accountsPage, addAccount, transactionsPage, addPayment, addExpense, reportsPage, usersPage, addUser, toggleUser, customersPage, suppliersPage, addCustomer, addSupplier, invoicesPage, addInvoice } from "../controllers/accountingController.js";
import { requireAuth, requireAdmin } from "../middleware/auth.js";

const router = express.Router();
router.get("/", homePage);
router.get("/login", showLogin);
router.post("/login", login);
router.post("/logout", requireAuth, logout);
router.get("/dashboard", requireAuth, dashboard);
router.get("/accounts", requireAuth, accountsPage);
router.post("/accounts", requireAuth, addAccount);
router.get("/transactions", requireAuth, transactionsPage);
router.get("/customers", requireAuth, customersPage);
router.post("/customers", requireAuth, addCustomer);
router.get("/suppliers", requireAuth, suppliersPage);
router.post("/suppliers", requireAuth, addSupplier);
router.get("/invoices", requireAuth, invoicesPage);
router.post("/invoices", requireAuth, addInvoice);
router.post("/payments", requireAuth, addPayment);
router.post("/expenses", requireAuth, addExpense);
router.get("/reports", requireAuth, reportsPage);
router.get("/users", requireAuth, requireAdmin, usersPage);
router.post("/users", requireAuth, requireAdmin, addUser);
router.post("/users/:id/toggle", requireAuth, requireAdmin, toggleUser);
export default router;
